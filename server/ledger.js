'use strict';

const db = require('./database');

let schemaReady;

// Keep cash earnings separate from point_wallets, which is a non-cash rewards
// system. A single immutable journal row represents a balanced posting:
// gross debit = creator credit (gross - fee) + platform fee credit.
async function ensureFinancialSchema() {
  if (!schemaReady) {
    schemaReady = (async () => {
      await db.query(`CREATE TABLE IF NOT EXISTS financial_ledger (
        id ${db.type === 'postgres'
          ? 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY'
          : db.type === 'mysql'
            ? 'BIGINT AUTO_INCREMENT PRIMARY KEY'
            : 'INTEGER PRIMARY KEY AUTOINCREMENT'},
        transaction_ref VARCHAR(160) NOT NULL UNIQUE,
        transaction_type VARCHAR(50) NOT NULL,
        debit_account VARCHAR(160) NOT NULL,
        credit_account VARCHAR(160) NOT NULL,
        fee_account VARCHAR(160),
        gross_minor BIGINT NOT NULL,
        fee_minor BIGINT NOT NULL DEFAULT 0,
        currency VARCHAR(3) NOT NULL,
        provider_ref VARCHAR(120),
        status VARCHAR(20) NOT NULL DEFAULT 'posted',
        created_at ${db.type === 'sqlite' ? 'DATETIME' : 'TIMESTAMP'} DEFAULT CURRENT_TIMESTAMP,
        CHECK (gross_minor > 0),
        CHECK (fee_minor >= 0 AND fee_minor <= gross_minor),
        CHECK (debit_account <> credit_account)
      )`);
      if (db.type === 'mysql') {
        const exists = await db.getOne(
          'SELECT index_name FROM information_schema.statistics WHERE table_schema = DATABASE() AND index_name = ?',
          ['financial_ledger_creator_idx'],
        );
        if (!exists) await db.query('CREATE INDEX financial_ledger_creator_idx ON financial_ledger (credit_account, created_at)');
      } else {
        await db.query('CREATE INDEX IF NOT EXISTS financial_ledger_creator_idx ON financial_ledger (credit_account, created_at)');
      }
    })().catch((error) => {
      schemaReady = null;
      throw error;
    });
  }
  await schemaReady;
}

function moneyToMinor(value) {
  const match = /^(\d{1,10})(?:\.(\d{1,2}))?$/.exec(String(value ?? '').trim());
  if (!match) return null;
  const amount = Number(match[1]) * 100 + Number((match[2] || '').padEnd(2, '0'));
  return Number.isSafeInteger(amount) && amount > 0 ? amount : null;
}

async function postLedgerEntry({ reference, type, debitAccount, creditAccount, feeAccount = null, grossMinor, feeMinor = 0, currency = 'NGN', providerRef = null }) {
  await ensureFinancialSchema();
  const amount = Number(grossMinor);
  const fee = Number(feeMinor);
  const code = String(currency || '').toUpperCase();
  if (!reference || String(reference).length > 160 || !type || !debitAccount || !creditAccount ||
      debitAccount === creditAccount || !Number.isSafeInteger(amount) || amount <= 0 ||
      !Number.isSafeInteger(fee) || fee < 0 || fee > amount || !/^[A-Z]{3}$/.test(code) || (fee > 0 && !feeAccount)) {
    throw new Error('Invalid balanced financial ledger posting.');
  }

  try {
    await db.insert(
      `INSERT INTO financial_ledger
       (transaction_ref, transaction_type, debit_account, credit_account, fee_account,
        gross_minor, fee_minor, currency, provider_ref, status)
       VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, 'posted')`,
      [String(reference), String(type), String(debitAccount), String(creditAccount), feeAccount,
        amount, fee, code, providerRef ? String(providerRef).slice(0, 120) : null],
    );
    return { created: true };
  } catch (error) {
    const duplicate = await db.getOne(
      'SELECT transaction_ref, transaction_type, debit_account, credit_account, fee_account, gross_minor, fee_minor, currency FROM financial_ledger WHERE transaction_ref = ?',
      [String(reference)],
    );
    if (!duplicate) throw error;
    // Idempotency must not silently accept the same reference for different money.
    if (duplicate.transaction_type !== String(type) || duplicate.debit_account !== String(debitAccount) ||
        duplicate.credit_account !== String(creditAccount) || Number(duplicate.gross_minor) !== amount ||
        Number(duplicate.fee_minor) !== fee || duplicate.currency !== code) {
      const conflict = new Error('A financial reference was already used for a different posting.');
      conflict.status = 409;
      throw conflict;
    }
    return { created: false };
  }
}

async function reconcileCreatorEarnings(userId) {
  await ensureFinancialSchema();
  const rows = await db.query(
    `SELECT checkout_id, seller_id, gross_amount, platform_fee, currency,
            flutterwave_transaction_id
       FROM payment_transactions
      WHERE seller_id = ? AND status = 'paid' AND checkout_id IS NOT NULL
      ORDER BY id ASC`,
    [userId],
  );
  for (const payment of rows) {
    const grossMinor = moneyToMinor(payment.gross_amount);
    const feeMinor = moneyToMinor(payment.platform_fee) ?? 0;
    if (!grossMinor || feeMinor > grossMinor) continue;
    await postLedgerEntry({
      reference: `creator-payment:${payment.checkout_id}`,
      type: 'verified_creator_sale',
      debitAccount: `gateway-clearing:${String(payment.currency || 'NGN').toUpperCase()}`,
      creditAccount: `creator-earnings:${userId}:${String(payment.currency || 'NGN').toUpperCase()}`,
      feeAccount: feeMinor ? `platform-revenue:${String(payment.currency || 'NGN').toUpperCase()}` : null,
      grossMinor,
      feeMinor,
      currency: payment.currency || 'NGN',
      providerRef: payment.flutterwave_transaction_id,
    });
  }
}

async function getCreatorLedger(userId, limit = 50) {
  await reconcileCreatorEarnings(userId);
  const rows = await db.query(
    `SELECT transaction_ref, transaction_type, gross_minor, fee_minor, currency,
            provider_ref, created_at
       FROM financial_ledger
      WHERE credit_account = ?
      ORDER BY id DESC LIMIT ?`,
    [`creator-earnings:${userId}:NGN`, Math.min(Math.max(Number(limit) || 50, 1), 100)],
  );
  return rows.map((row) => ({
    reference: row.transaction_ref,
    type: row.transaction_type,
    grossAmount: (Number(row.gross_minor) / 100).toFixed(2),
    platformFee: (Number(row.fee_minor) / 100).toFixed(2),
    creatorShare: ((Number(row.gross_minor) - Number(row.fee_minor)) / 100).toFixed(2),
    currency: row.currency,
    providerReference: row.provider_ref || null,
    createdAt: row.created_at,
    status: 'verified',
  }));
}

async function getCreatorEarningsSummary(userId) {
  const transactions = await getCreatorLedger(userId, 100);
  const totals = {};
  for (const row of transactions) {
    totals[row.currency] ||= { grossMinor: 0, feeMinor: 0, creatorMinor: 0 };
    totals[row.currency].grossMinor += moneyToMinor(row.grossAmount) || 0;
    totals[row.currency].feeMinor += moneyToMinor(row.platformFee) || 0;
    totals[row.currency].creatorMinor += moneyToMinor(row.creatorShare) || 0;
  }
  return {
    earnings: Object.entries(totals).map(([currency, value]) => ({
      currency,
      gross: (value.grossMinor / 100).toFixed(2),
      platformFee: (value.feeMinor / 100).toFixed(2),
      creatorShare: (value.creatorMinor / 100).toFixed(2),
    })),
    transactions,
    withdrawable: false,
    settlementNote: 'These are verified creator sales. Settlement is handled by the configured payment provider; this endpoint does not represent a withdrawable wallet balance.',
  };
}

module.exports = { ensureFinancialSchema, getCreatorEarningsSummary, getCreatorLedger, moneyToMinor, postLedgerEntry, reconcileCreatorEarnings };
