const express = require('express');
const bcrypt = require('bcryptjs');
const jwt = require('jsonwebtoken');
const crypto = require('crypto');
const db = require('./database');

const router = express.Router();
const dateType = db.type === 'sqlite' ? 'DATETIME' : 'TIMESTAMP';
const JWT_SECRET = process.env.ADMIN_JWT_SECRET || `${process.env.JWT_SECRET || 'quickchat-local-development-secret'}:independent-admin`;

function signAdminToken(account) {
  return jwt.sign(
    { adminId: account.id, actorUserId: account.actor_user_id, type: 'quickchat-admin' },
    JWT_SECRET,
    { expiresIn: '8h', issuer: 'quickchat-admin', audience: 'quickchat-admin-console' },
  );
}

async function initializeAdminAuth() {
  const idColumn = db.type === 'postgres'
    ? 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY'
    : db.type === 'mysql'
      ? 'INTEGER AUTO_INCREMENT PRIMARY KEY'
      : 'INTEGER PRIMARY KEY AUTOINCREMENT';

  await db.query(`CREATE TABLE IF NOT EXISTS admin_accounts (
    id ${idColumn},
    username VARCHAR(80) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    actor_user_id INTEGER NOT NULL UNIQUE REFERENCES users(id) ON DELETE RESTRICT,
    must_change_password INTEGER NOT NULL DEFAULT 1,
    is_active INTEGER NOT NULL DEFAULT 1,
    failed_attempts INTEGER NOT NULL DEFAULT 0,
    locked_until ${dateType},
    last_login_at ${dateType},
    created_at ${dateType} DEFAULT CURRENT_TIMESTAMP,
    updated_at ${dateType} DEFAULT CURRENT_TIMESTAMP
  )`);

  const existing = await db.getOne('SELECT id FROM admin_accounts LIMIT 1');
  if (existing) return;

  const random = crypto.randomBytes(18).toString('hex');
  const actorUsername = `qc-admin-actor-${random.slice(0, 12)}`;
  const actorEmail = `admin-system-${random}@internal.quickchat.invalid`;
  const actorPassword = await bcrypt.hash(crypto.randomBytes(48).toString('hex'), 12);
  const actor = await db.insert(
    'INSERT INTO users (fullname, name, username, email, password, googleid) VALUES (?, ?, ?, ?, ?, ?)',
    ['QuickChat Administration Service', 'QuickChat Administration Service', actorUsername, actorEmail, actorPassword, null],
  );
  if (!actor?.id) throw new Error('[Admin auth] Could not create the internal administration service principal.');
  await db.update('UPDATE users SET is_synthetic = 1 WHERE id = ?', [actor.id]).catch(() => {});

  const role = await db.getOne("SELECT id FROM admin_roles WHERE role_key = 'super_admin' AND is_active = 1");
  if (!role) throw new Error('[Admin auth] The Super Administrator role is missing.');
  await db.query(
    'INSERT INTO admin_user_roles (user_id, role_id, assigned_by, is_active) VALUES (?, ?, ?, 1) ' +
      (db.type === 'mysql'
        ? 'ON DUPLICATE KEY UPDATE is_active = 1'
        : 'ON CONFLICT(user_id, role_id) DO UPDATE SET is_active = 1'),
    [actor.id, role.id, actor.id],
  );

  const passwordHash = await bcrypt.hash('admin123', 12);
  await db.insert(
    'INSERT INTO admin_accounts (username, password_hash, actor_user_id, must_change_password) VALUES (?, ?, ?, 1)',
    ['admin', passwordHash, actor.id],
  );
  await db.insert(
    'INSERT INTO admin_audit_logs (admin_user_id, action, target_type, target_id, reason, new_state) VALUES (?, ?, ?, ?, ?, ?)',
    [actor.id, 'admin.independent_account_bootstrapped', 'admin_account', '1', 'Independent admin console initialized', JSON.stringify({ username: 'admin', mustChangePassword: true })],
  );
  console.log('[Admin auth] Independent admin console initialized. Change the bootstrap password after first login.');
}

async function authenticateAdmin(req, res, next) {
  const authorization = req.get('authorization') || '';
  const token = authorization.startsWith('Bearer ') ? authorization.slice(7).trim() : '';
  if (!token) return res.status(401).json({ message: 'Sign in to the administration centre.' });
  try {
    const session = jwt.verify(token, JWT_SECRET, {
      issuer: 'quickchat-admin',
      audience: 'quickchat-admin-console',
    });
    if (session.type !== 'quickchat-admin' || !Number.isSafeInteger(Number(session.adminId))) {
      return res.status(401).json({ message: 'Invalid administration session.' });
    }
    const account = await db.getOne(
      'SELECT id, username, actor_user_id, must_change_password, is_active FROM admin_accounts WHERE id = ?',
      [Number(session.adminId)],
    );
    if (!account || !Number(account.is_active) || Number(account.actor_user_id) !== Number(session.actorUserId)) {
      return res.status(401).json({ message: 'This administration session is no longer active.' });
    }
    req.adminAccount = account;
    // The service principal exists only to satisfy the legacy governance tables'
    // actor foreign keys. It has a random password and cannot authenticate as a user.
    req.user = { id: Number(account.actor_user_id), username: account.username };
    return next();
  } catch (error) {
    if (['JsonWebTokenError', 'TokenExpiredError', 'NotBeforeError'].includes(error?.name)) {
      return res.status(401).json({ message: 'Your administration session has expired. Sign in again.' });
    }
    return next(error);
  }
}

router.post('/admin/auth/login', async (req, res, next) => {
  try {
    const username = String(req.body?.username || '').trim();
    const password = String(req.body?.password || '');
    if (!username || !password) return res.status(400).json({ message: 'Enter your administrator username and password.' });
    const account = await db.getOne(
      'SELECT id, username, password_hash, actor_user_id, must_change_password, is_active, failed_attempts, locked_until FROM admin_accounts WHERE LOWER(username) = LOWER(?)',
      [username],
    );
    if (!account || !Number(account.is_active)) return res.status(401).json({ message: 'Invalid administrator username or password.' });
    if (account.locked_until && new Date(account.locked_until).getTime() > Date.now()) {
      return res.status(429).json({ message: 'Too many failed attempts. Try again after the temporary lock expires.' });
    }
    const valid = await bcrypt.compare(password, account.password_hash);
    if (!valid) {
      const attempts = Number(account.failed_attempts || 0) + 1;
      const lockUntil = attempts >= 5 ? new Date(Date.now() + 15 * 60 * 1000).toISOString() : null;
      await db.update(
        'UPDATE admin_accounts SET failed_attempts = ?, locked_until = ?, updated_at = CURRENT_TIMESTAMP WHERE id = ?',
        [attempts >= 5 ? 0 : attempts, lockUntil, account.id],
      );
      return res.status(attempts >= 5 ? 429 : 401).json({
        message: attempts >= 5 ? 'Too many failed attempts. Try again in 15 minutes.' : 'Invalid administrator username or password.',
      });
    }
    await db.update(
      'UPDATE admin_accounts SET failed_attempts = 0, locked_until = NULL, last_login_at = CURRENT_TIMESTAMP, updated_at = CURRENT_TIMESTAMP WHERE id = ?',
      [account.id],
    );
    const token = signAdminToken(account);
    res.json({
      token,
      admin: { id: account.id, username: account.username, mustChangePassword: Boolean(Number(account.must_change_password)) },
    });
  } catch (error) { next(error); }
});

router.post('/admin/auth/credentials', async (req, res, next) => {
  try {
    const account = req.adminAccount;
    const currentPassword = String(req.body?.currentPassword || '');
    const newUsername = String(req.body?.newUsername || account.username).trim();
    const newPassword = String(req.body?.newPassword || '');
    if (!currentPassword) return res.status(400).json({ message: 'Enter your current password to confirm this change.' });
    if (!/^[a-zA-Z0-9._-]{3,80}$/.test(newUsername)) {
      return res.status(400).json({ message: 'Username must be 3–80 characters and may contain letters, numbers, dots, underscores and hyphens.' });
    }
    if (!newPassword && newUsername.toLowerCase() === account.username.toLowerCase()) {
      return res.status(400).json({ message: 'Enter a new username or a new password.' });
    }
    if (newPassword && newPassword.length < 12) {
      return res.status(400).json({ message: 'Use at least 12 characters for the new password.' });
    }
    const saved = await db.getOne('SELECT password_hash FROM admin_accounts WHERE id = ?', [account.id]);
    if (!saved || !(await bcrypt.compare(currentPassword, saved.password_hash))) {
      return res.status(401).json({ message: 'Your current password is incorrect.' });
    }
    const duplicate = await db.getOne(
      'SELECT id FROM admin_accounts WHERE LOWER(username) = LOWER(?) AND id <> ?',
      [newUsername, account.id],
    );
    if (duplicate) return res.status(409).json({ message: 'That administrator username is already in use.' });

    const passwordHash = newPassword ? await bcrypt.hash(newPassword, 12) : saved.password_hash;
    await db.update(
      'UPDATE admin_accounts SET username = ?, password_hash = ?, must_change_password = 0, updated_at = CURRENT_TIMESTAMP WHERE id = ?',
      [newUsername, passwordHash, account.id],
    );
    await db.insert(
      'INSERT INTO admin_audit_logs (admin_user_id, action, target_type, target_id, reason, new_state) VALUES (?, ?, ?, ?, ?, ?)',
      [account.actor_user_id, 'admin.credentials_changed', 'admin_account', account.id, 'Administrator credentials updated', JSON.stringify({ username: newUsername })],
    );
    const refreshed = { ...account, username: newUsername };
    res.json({
      message: 'Administrator credentials updated. Sign in again using the new credentials.',
      token: signAdminToken(refreshed),
      admin: { id: account.id, username: newUsername, mustChangePassword: false },
    });
  } catch (error) { next(error); }
});

router.get('/admin/auth/session', (req, res) => {
  res.json({
    admin: {
      id: req.adminAccount.id,
      username: req.adminAccount.username,
      mustChangePassword: Boolean(Number(req.adminAccount.must_change_password)),
    },
  });
});

module.exports = { router, initializeAdminAuth, authenticateAdmin };
