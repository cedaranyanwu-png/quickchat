router.post('/rewards-program/withdrawals', asyncRoute(async (req, res) => {
  const amount = Math.round(Number(req.body?.amount) * 100);
  if (!Number.isSafeInteger(amount) || amount < MIN_WITHDRAWAL_KOBO) return res.status(400).json({ message: 'Minimum withdrawal is ₦100.' });
  const account = await db.getOne("SELECT bank_name, account_name, account_masked FROM flutterwave_creator_accounts WHERE user_id = ? AND status = 'active'", [req.user.id]);
  if (!account) return res.status(409).json({ message: 'Connect and verify your payout bank account in Settings first.' });
  const pending = await db.getOne("SELECT id FROM qc_reward_withdrawals WHERE user_id = ? AND status = 'pending'", [req.user.id]);
  if (pending) return res.status(409).json({ message: 'You already have a pending withdrawal request.' });
  await ensureWallet(req.user.id);
  const debited = await db.update('UPDATE qc_reward_wallets SET cash_kobo = cash_kobo - ? WHERE user_id = ? AND cash_kobo >= ?', [amount, req.user.id, amount]);
  if (!debited) return res.status(402).json({ message: 'Insufficient withdrawable balance.' });
  try {
    const reference = `qcpayout_${req.user.id}_${crypto.randomUUID()}`;
    const row = await db.insert('INSERT INTO qc_reward_withdrawals (user_id, amount_kobo, bank_name, account_name, account_masked, reference) VALUES (?, ?, ?, ?, ?, ?)',
      [req.user.id, amount, account.bank_name, account.account_name, account.account_masked, reference]);
    await db.insert('INSERT INTO qc_reward_ledger (user_id, asset, amount, kind, reference) VALUES (?, ?, ?, ?, ?)', [req.user.id, 'cash', -amount, 'withdrawal_hold', `${reference}_hold`]);
    res.status(201).json({ message: 'Withdrawal request sent for admin review.', withdrawal: row });
  } catch (error) {
    await db.update('UPDATE qc_reward_wallets SET cash_kobo = cash_kobo + ? WHERE user_id = ?', [amount, req.user.id]);
    throw error;
  }
}));
router.post('/rewards-program/tasks/:taskId/complete', asyncRoute(async (req, res) => {
  const taskId = Number(req.params.taskId);
  const task = await db.getOne('SELECT * FROM qc_reward_tasks WHERE id = ? AND is_active = 1', [taskId]);
  if (!task) return res.status(404).json({ message: 'Task is unavailable.' });
  if (task.task_type === 'profile') {
    const profile = await db.getOne('SELECT bio, picture, avatar_url FROM users WHERE id = ?', [req.user.id]);
    if (!profile || !String(profile.bio || '').trim() || !(profile.picture || profile.avatar_url)) return res.status(400).json({ message: 'Add a profile photo and bio before completing this task.' });
  } else {
    return res.status(400).json({ message: 'This task requires server-side verification and cannot be self-reported.' });
  }
  const reference = `task_${task.id}_user_${req.user.id}`;
  try { await db.insert('INSERT INTO qc_reward_task_completions (task_id, user_id, reference) VALUES (?, ?, ?)', [task.id, req.user.id, reference]); }
  catch (error) { if (uniqueError(error)) return res.status(409).json({ message: 'You have already completed this task.' }); throw error; }
  await ledgerCredit(req.user.id, 'task_reward', Number(task.points), `task_points_${task.id}_user_${req.user.id}`);
  res.json({ message: `Task completed. You earned ${task.points} points.` });
}));
