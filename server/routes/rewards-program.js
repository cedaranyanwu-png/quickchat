const express = require('express');
const crypto = require('node:crypto');
const db = require('../database');
const { sendEmail } = require('../email');
const { requirePermission, audit } = require('./admin');

const router = express.Router();
const idColumn = db.type === 'postgres' ? 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY'
  : db.type === 'mysql' ? 'INTEGER AUTO_INCREMENT PRIMARY KEY' : 'INTEGER PRIMARY KEY AUTOINCREMENT';
const dateType = db.type === 'sqlite' ? 'DATETIME' : 'TIMESTAMP';
const POINT_VALUE_NAIRA = 10; // 100 QuickChat programme points = ₦1,000
const REGISTRATION_POINTS = 100;
const DAILY_STAR = 1;
const STAR_CONVERSION = 100;
const REFERRAL_POINTS = 20;
const MIN_WITHDRAWAL_KOBO = 10000;

function asyncRoute(handler) {
  return (req, res, next) => Promise.resolve(handler(req, res, next)).catch(next);
}
function uniqueError(error) {
  return ['23505', 'SQLITE_CONSTRAINT', 'ER_DUP_ENTRY'].includes(error?.code) ||
    /unique constraint|duplicate key/i.test(String(error?.message || ''));
}
function localDay() {
  return new Intl.DateTimeFormat('en-CA', { timeZone: 'Africa/Lagos', year: 'numeric', month: '2-digit', day: '2-digit' }).format(new Date());
}
async function ensureWallet(userId) {
  await db.query('INSERT INTO qc_reward_wallets (user_id) VALUES (?) ' +
    (db.type === 'mysql' ? 'ON DUPLICATE KEY UPDATE user_id = VALUES(user_id)' : 'ON CONFLICT(user_id) DO NOTHING'), [userId]);
}
async function ledgerCredit(userId, kind, amount, reference) {
  const value = Math.trunc(Number(amount));
  if (!Number.isSafeInteger(value) || value <= 0 || !reference) return false;
  await ensureWallet(userId);
  try {
    await db.insert('INSERT INTO qc_reward_ledger (user_id, asset, amount, kind, reference) VALUES (?, ?, ?, ?, ?)',
      [userId, 'points', value, kind, reference]);
  } catch (error) {
    if (uniqueError(error)) return false;
    throw error;
  }
  await db.update('UPDATE qc_reward_wallets SET points = points + ?, updated_at = CURRENT_TIMESTAMP WHERE user_id = ?', [value, userId]);
  return true;
}
async function initializeRewardProgram() {
  const statements = [
    `CREATE TABLE IF NOT EXISTS qc_reward_wallets (
      user_id INTEGER PRIMARY KEY, stars INTEGER NOT NULL DEFAULT 0, points INTEGER NOT NULL DEFAULT 0,
      cash_kobo BIGINT NOT NULL DEFAULT 0, updated_at ${dateType} DEFAULT CURRENT_TIMESTAMP)`,
    `CREATE TABLE IF NOT EXISTS qc_reward_ledger (
      id ${idColumn}, user_id INTEGER NOT NULL, asset VARCHAR(12) NOT NULL, amount BIGINT NOT NULL,
      kind VARCHAR(40) NOT NULL, reference VARCHAR(180) NOT NULL UNIQUE, note TEXT,
      created_at ${dateType} DEFAULT CURRENT_TIMESTAMP)`,
    `CREATE TABLE IF NOT EXISTS qc_reward_withdrawals (
      id ${idColumn}, user_id INTEGER NOT NULL, amount_kobo BIGINT NOT NULL,
      bank_name VARCHAR(120) NOT NULL, account_name VARCHAR(120) NOT NULL, account_masked VARCHAR(32) NOT NULL,
      reference VARCHAR(180) NOT NULL UNIQUE, status VARCHAR(20) NOT NULL DEFAULT 'pending', admin_note TEXT,
      reviewed_by INTEGER, reviewed_at ${dateType}, created_at ${dateType} DEFAULT CURRENT_TIMESTAMP)`,
    `CREATE TABLE IF NOT EXISTS qc_reward_daily_claims (
      id ${idColumn}, user_id INTEGER NOT NULL, claim_day VARCHAR(10) NOT NULL,
      created_at ${dateType} DEFAULT CURRENT_TIMESTAMP, UNIQUE(user_id, claim_day))`,
    `CREATE TABLE IF NOT EXISTS qc_reward_referrals (
      id ${idColumn}, referrer_id INTEGER NOT NULL, referred_user_id INTEGER NOT NULL UNIQUE,
      status VARCHAR(20) NOT NULL DEFAULT 'pending', qualified_at ${dateType},
      created_at ${dateType} DEFAULT CURRENT_TIMESTAMP)`,
    `CREATE TABLE IF NOT EXISTS qc_reward_tasks (
      id ${idColumn}, task_key VARCHAR(80) NOT NULL UNIQUE, title VARCHAR(160) NOT NULL,
      description TEXT, points INTEGER NOT NULL DEFAULT 0, task_type VARCHAR(24) NOT NULL DEFAULT 'manual',
      target_count INTEGER NOT NULL DEFAULT 1, is_active INTEGER NOT NULL DEFAULT 1,
      created_at ${dateType} DEFAULT CURRENT_TIMESTAMP, updated_at ${dateType} DEFAULT CURRENT_TIMESTAMP)`,
    `CREATE TABLE IF NOT EXISTS qc_reward_task_completions (
      id ${idColumn}, task_id INTEGER NOT NULL, user_id INTEGER NOT NULL,
      reference VARCHAR(180) NOT NULL UNIQUE, created_at ${dateType} DEFAULT CURRENT_TIMESTAMP)`,
    `CREATE TABLE IF NOT EXISTS qc_notification_campaigns (
      id ${idColumn}, admin_user_id INTEGER NOT NULL, title VARCHAR(160) NOT NULL, message TEXT NOT NULL,
      channels VARCHAR(40) NOT NULL, audience VARCHAR(40) NOT NULL, status VARCHAR(20) NOT NULL DEFAULT 'queued',
      recipient_count INTEGER NOT NULL DEFAULT 0, sent_count INTEGER NOT NULL DEFAULT 0,
      failed_count INTEGER NOT NULL DEFAULT 0, created_at ${dateType} DEFAULT CURRENT_TIMESTAMP)`,
    `CREATE TABLE IF NOT EXISTS qc_notification_popups (
      id ${idColumn}, user_id INTEGER NOT NULL, campaign_id INTEGER NOT NULL,
      title VARCHAR(160) NOT NULL, message TEXT NOT NULL, is_read INTEGER NOT NULL DEFAULT 0,
      created_at ${dateType} DEFAULT CURRENT_TIMESTAMP, UNIQUE(user_id, campaign_id))`,
    `CREATE TABLE IF NOT EXISTS qc_notification_delivery_logs (
      id ${idColumn}, campaign_id INTEGER NOT NULL, user_id INTEGER NOT NULL,
      channel VARCHAR(20) NOT NULL, status VARCHAR(20) NOT NULL, error TEXT,
      created_at ${dateType} DEFAULT CURRENT_TIMESTAMP, UNIQUE(campaign_id, user_id, channel))`,
  ];
  for (const sql of statements) await db.query(sql);
  await db.query(
    'INSERT INTO qc_reward_tasks (task_key, title, description, points, task_type, target_count, is_active) VALUES (?, ?, ?, ?, ?, ?, 1) ' +
    (db.type === 'mysql' ? 'ON DUPLICATE KEY UPDATE task_key = VALUES(task_key)' : 'ON CONFLICT(task_key) DO NOTHING'),
    ['complete_profile', 'Complete your profile', 'Add a profile photo and a short bio.', 10, 'profile', 1],
  );
}
async function createReferral(referrerId, referredUserId) {
  if (!referrerId || Number(referrerId) === Number(referredUserId)) return;
  const exists = await db.getOne('SELECT id FROM users WHERE id = ?', [referrerId]);
  if (!exists) return;
  try {
    await db.insert('INSERT INTO qc_reward_referrals (referrer_id, referred_user_id) VALUES (?, ?)', [referrerId, referredUserId]);
  } catch (error) { if (!uniqueError(error)) throw error; }
}
async function qualifyNewUser(userId) {
  await ensureWallet(userId);
  await ledgerCredit(userId, 'registration_bonus', REGISTRATION_POINTS, `registration_${userId}`);
  const referral = await db.getOne("SELECT * FROM qc_reward_referrals WHERE referred_user_id = ? AND status = 'pending'", [userId]);
  if (referral) {
    // A referral qualifies only after the invitee verifies their email and returns on a separate day.
    const claims = await db.getCount('SELECT COUNT(*) AS count FROM qc_reward_daily_claims WHERE user_id = ?', [userId]);
    if (claims >= 1) {
      await ledgerCredit(referral.referrer_id, 'referral_reward', REFERRAL_POINTS, `referral_${userId}`);
      await db.update("UPDATE qc_reward_referrals SET status = 'qualified', qualified_at = CURRENT_TIMESTAMP WHERE id = ? AND status = 'pending'", [referral.id]);
    }
  }
}
