router.get('/rewards-program/me', asyncRoute(async (req, res) => {
  await ensureWallet(req.user.id);
  const wallet = await db.getOne('SELECT stars, points, cash_kobo FROM qc_reward_wallets WHERE user_id = ?', [req.user.id]);
  const tasks = await db.query(`SELECT t.id, t.task_key, t.title, t.description, t.points, t.task_type, t.target_count,
    CASE WHEN c.id IS NULL THEN 0 ELSE 1 END AS completed
    FROM qc_reward_tasks t LEFT JOIN qc_reward_task_completions c ON c.task_id = t.id AND c.user_id = ?
    WHERE t.is_active = 1 ORDER BY t.id`, [req.user.id]);
  const referralCount = await db.getCount("SELECT COUNT(*) AS count FROM qc_reward_referrals WHERE referrer_id = ? AND status = 'qualified'", [req.user.id]);
  const lastClaim = await db.getOne('SELECT claim_day FROM qc_reward_daily_claims WHERE user_id = ? ORDER BY claim_day DESC LIMIT 1', [req.user.id]);
  res.json({ stars: Number(wallet?.stars || 0), points: Number(wallet?.points || 0),
    cashBalance: (Number(wallet?.cash_kobo || 0) / 100).toFixed(2), pointValueNaira: POINT_VALUE_NAIRA,
    starConversion: STAR_CONVERSION, dailyStar: DAILY_STAR, referralPoints: REFERRAL_POINTS,
    referralCode: `QC${req.user.id}`, referralLink: `${String(process.env.PUBLIC_APP_URL || '').replace(/\/$/, '')}/register?ref=QC${req.user.id}`,
    referrals: referralCount, lastClaimDay: lastClaim?.claim_day || null, today: localDay(), tasks });
}));
router.post('/rewards-program/daily-claim', asyncRoute(async (req, res) => {
  const day = localDay();
  try {
    await db.insert('INSERT INTO qc_reward_daily_claims (user_id, claim_day) VALUES (?, ?)', [req.user.id, day]);
  } catch (error) {
    if (uniqueError(error)) return res.status(409).json({ message: 'Your daily Star has already been claimed today.' });
    throw error;
  }
  await ensureWallet(req.user.id);
  await db.update('UPDATE qc_reward_wallets SET stars = stars + 1, updated_at = CURRENT_TIMESTAMP WHERE user_id = ?', [req.user.id]);
  const referral = await db.getOne("SELECT * FROM qc_reward_referrals WHERE referred_user_id = ? AND status = 'pending'", [req.user.id]);
  if (referral) {
    await ledgerCredit(referral.referrer_id, 'referral_reward', REFERRAL_POINTS, `referral_${req.user.id}`);
    await db.update("UPDATE qc_reward_referrals SET status = 'qualified', qualified_at = CURRENT_TIMESTAMP WHERE id = ? AND status = 'pending'", [referral.id]);
  }
  const wallet = await db.getOne('SELECT stars FROM qc_reward_wallets WHERE user_id = ?', [req.user.id]);
  res.json({ message: 'Daily Star claimed.', stars: Number(wallet?.stars || 0) });
}));
router.post('/rewards-program/convert-stars', asyncRoute(async (req, res) => {
  const wallet = await db.getOne('SELECT stars FROM qc_reward_wallets WHERE user_id = ?', [req.user.id]);
  const stars = Number(wallet?.stars || 0);
  const batches = Math.floor(stars / STAR_CONVERSION);
  if (!batches) return res.status(400).json({ message: 'You need 100 Stars before converting them.' });
  const converted = batches * STAR_CONVERSION;
  await ensureWallet(req.user.id);
  const changed = await db.update('UPDATE qc_reward_wallets SET stars = stars - ?, updated_at = CURRENT_TIMESTAMP WHERE user_id = ? AND stars >= ?', [converted, req.user.id, converted]);
  if (!changed) return res.status(409).json({ message: 'Your Star balance changed. Refresh and try again.' });
  const credited = await ledgerCredit(req.user.id, 'star_conversion', batches * 100, `stars_to_points_${req.user.id}_${crypto.randomUUID()}`);
  if (!credited) {
    await db.update('UPDATE qc_reward_wallets SET stars = stars + ? WHERE user_id = ?', [converted, req.user.id]);
    return res.status(409).json({ message: 'Conversion could not be recorded. Try again.' });
  }
  const updated = await db.getOne('SELECT stars, points FROM qc_reward_wallets WHERE user_id = ?', [req.user.id]);
  res.json({ message: `${converted} Stars converted to ${batches * 100} Points.`, ...updated });
}));
router.post('/rewards-program/convert-points', asyncRoute(async (req, res) => {
  const points = Math.trunc(Number(req.body?.points));
  if (!Number.isSafeInteger(points) || points < 100 || points % 100 !== 0) return res.status(400).json({ message: 'Convert points in multiples of 100.' });
  await ensureWallet(req.user.id);
  const debit = await db.update('UPDATE qc_reward_wallets SET points = points - ?, updated_at = CURRENT_TIMESTAMP WHERE user_id = ? AND points >= ?', [points, req.user.id, points]);
  if (!debit) return res.status(402).json({ message: 'Insufficient QuickChat reward points.' });
  const nairaKobo = points * POINT_VALUE_NAIRA * 100;
  const ref = `points_cash_${req.user.id}_${crypto.randomUUID()}`;
  try {
    await db.insert('INSERT INTO qc_reward_ledger (user_id, asset, amount, kind, reference) VALUES (?, ?, ?, ?, ?)', [req.user.id, 'points', -points, 'cash_conversion', `${ref}_debit`]);
    await db.insert('INSERT INTO qc_reward_ledger (user_id, asset, amount, kind, reference) VALUES (?, ?, ?, ?, ?)', [req.user.id, 'cash', nairaKobo, 'cash_conversion', `${ref}_credit`]);
    await db.update('UPDATE qc_reward_wallets SET cash_kobo = cash_kobo + ?, updated_at = CURRENT_TIMESTAMP WHERE user_id = ?', [nairaKobo, req.user.id]);
  } catch (error) {
    await db.update('UPDATE qc_reward_wallets SET points = points + ? WHERE user_id = ?', [points, req.user.id]);
    throw error;
  }
  const updated = await db.getOne('SELECT points, cash_kobo FROM qc_reward_wallets WHERE user_id = ?', [req.user.id]);
  res.json({ message: `₦${(nairaKobo / 100).toLocaleString('en-NG')} added to your withdrawable QuickChat balance.`,
    points: Number(updated.points), cashBalance: (Number(updated.cash_kobo) / 100).toFixed(2) });
}));
