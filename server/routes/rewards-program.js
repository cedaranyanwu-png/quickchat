router.post('/admin/notifications', requirePermission('notifications.send'), asyncRoute(async (req, res) => {
  const title = String(req.body?.title || '').trim().slice(0, 160);
  const message = String(req.body?.message || '').trim().slice(0, 4000);
  const channels = [...new Set((Array.isArray(req.body?.channels) ? req.body.channels : []).map(String))].filter(c => ['in_app','email','popup'].includes(c));
  const audience = String(req.body?.audience || 'everyone');
  if (!title || !message || !channels.length || !['everyone','verified','active','inactive','new_users'].includes(audience)) return res.status(400).json({ message: 'Enter a title, message, valid audience and at least one delivery channel.' });
  const filters = { everyone: 'WHERE COALESCE(is_synthetic,0) = 0', verified: 'WHERE COALESCE(email_verified,0) = 1 AND COALESCE(is_synthetic,0) = 0', active: "WHERE createdat >= CURRENT_TIMESTAMP - INTERVAL '30 days' AND COALESCE(is_synthetic,0) = 0", inactive: "WHERE createdat < CURRENT_TIMESTAMP - INTERVAL '30 days' AND COALESCE(is_synthetic,0) = 0", new_users: "WHERE createdat >= CURRENT_TIMESTAMP - INTERVAL '7 days' AND COALESCE(is_synthetic,0) = 0" };
  let audienceSql = filters[audience];
  if (db.type === 'sqlite') audienceSql = ({ active: "WHERE createdat >= datetime('now','-30 days') AND COALESCE(is_synthetic,0) = 0", inactive: "WHERE createdat < datetime('now','-30 days') AND COALESCE(is_synthetic,0) = 0", new_users: "WHERE createdat >= datetime('now','-7 days') AND COALESCE(is_synthetic,0) = 0" })[audience] || audienceSql;
  if (db.type === 'mysql') audienceSql = ({ active: "WHERE createdat >= DATE_SUB(CURRENT_TIMESTAMP, INTERVAL 30 DAY) AND COALESCE(is_synthetic,0) = 0", inactive: "WHERE createdat < DATE_SUB(CURRENT_TIMESTAMP, INTERVAL 30 DAY) AND COALESCE(is_synthetic,0) = 0", new_users: "WHERE createdat >= DATE_SUB(CURRENT_TIMESTAMP, INTERVAL 7 DAY) AND COALESCE(is_synthetic,0) = 0" })[audience] || audienceSql;
  const recipients = await db.query(`SELECT id, email, fullname FROM users ${audienceSql} ORDER BY id`);
  const campaign = await db.insert('INSERT INTO qc_notification_campaigns (admin_user_id, title, message, channels, audience, recipient_count) VALUES (?, ?, ?, ?, ?, ?)',
    [req.user.id, title, message, channels.join(','), audience, recipients.length]);
  await audit(req, 'notification.campaign_created', 'notification_campaign', campaign.id, 'Notification campaign queued', null, { title, channels, audience, recipients: recipients.length });
  res.status(202).json({ message: 'Notification campaign queued for background delivery.', campaignId: campaign.id, recipients: recipients.length });
  setImmediate(async () => {
    let sent = 0, failed = 0;
    for (const user of recipients) {
      for (const channel of channels) {
        try {
          if (channel === 'in_app') {
            await db.insert('INSERT INTO notifications (user_id, actor_id, type, text, is_read) VALUES (?, NULL, ?, ?, 0)', [user.id, 'system', message.slice(0,255)]);
          } else if (channel === 'popup') {
            await db.insert('INSERT INTO qc_notification_popups (user_id, campaign_id, title, message) VALUES (?, ?, ?, ?)', [user.id, campaign.id, title, message]);
          } else if (channel === 'email') {
            if (!user.email) throw new Error('No email address on account.');
            const result = await sendEmail({ to: user.email, subject: title, text: message, html: `<div style="font-family:Arial,sans-serif;max-width:600px;margin:auto;padding:24px"><h2>${title.replace(/[&<>"]/g, '')}</h2><p style="white-space:pre-wrap">${message.replace(/[&<>"]/g, '')}</p><p>QuickChat</p></div>` });
            if (!result.delivered) throw new Error('Email provider returned preview mode, not a delivered email.');
          }
          await db.insert('INSERT INTO qc_notification_delivery_logs (campaign_id, user_id, channel, status) VALUES (?, ?, ?, ?)', [campaign.id, user.id, channel, 'sent']);
          sent++;
        } catch (error) {
          failed++;
          try { await db.insert('INSERT INTO qc_notification_delivery_logs (campaign_id, user_id, channel, status, error) VALUES (?, ?, ?, ?, ?)', [campaign.id, user.id, channel, 'failed', String(error.message).slice(0,1000)]); } catch (_ignored) {}
        }
      }
    }
    await db.update('UPDATE qc_notification_campaigns SET sent_count = ?, failed_count = ?, status = ? WHERE id = ?', [sent, failed, failed ? 'completed_with_errors' : 'completed', campaign.id]);
  });
}));
