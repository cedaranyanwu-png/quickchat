const express = require('express');
const db = require('../database');
const { requirePermission, audit } = require('./admin');

const router = express.Router();
const idColumn = db.type === 'postgres'
  ? 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY'
  : db.type === 'mysql'
    ? 'INTEGER AUTO_INCREMENT PRIMARY KEY'
    : 'INTEGER PRIMARY KEY AUTOINCREMENT';
const dateType = db.type === 'sqlite' ? 'DATETIME' : 'TIMESTAMP';
const GOAL = 100;

function asyncRoute(handler) {
  return (req, res, next) => Promise.resolve(handler(req, res, next)).catch(next);
}

async function initializeFirst100Tables() {
  await db.query(`CREATE TABLE IF NOT EXISTS qc_first100_members (
    id ${idColumn}, user_id INTEGER NOT NULL UNIQUE,
    source VARCHAR(40) NOT NULL DEFAULT 'direct',
    joined_at ${dateType} DEFAULT CURRENT_TIMESTAMP
  )`);
}

router.get('/growth/first-100', asyncRoute(async (req, res) => {
  const joined = await db.getCount('SELECT COUNT(*) AS count FROM qc_first100_members');
  const latest = await db.query(`SELECT m.joined_at, u.fullname, u.username, u.picture, u.avatar_url
    FROM qc_first100_members m JOIN users u ON u.id = m.user_id
    WHERE COALESCE(u.is_synthetic, 0) = 0
    ORDER BY m.id DESC LIMIT 12`);
  res.json({
    goal: GOAL,
    joined: Number(joined || 0),
    remaining: Math.max(0, GOAL - Number(joined || 0)),
    full: Number(joined || 0) >= GOAL,
    members: latest.map((row) => ({
      fullname: row.fullname || row.username || 'QuickChat member',
      username: row.username || '',
      picture: row.picture || row.avatar_url || null,
      joinedAt: row.joined_at,
    })),
  });
}));

router.post('/growth/first-100/join', asyncRoute(async (req, res) => {
  const existing = await db.getOne('SELECT id FROM qc_first100_members WHERE user_id = ?', [req.user.id]);
  if (existing) {
    return res.json({
      joined: true,
      message: 'You are already one of the QuickChat First 100.',
      referralCode: `QC${req.user.id}`,
      referralLink: `${String(process.env.PUBLIC_APP_URL || '').replace(/\/$/, '')}/register?ref=QC${req.user.id}`,
    });
  }
  const count = await db.getCount('SELECT COUNT(*) AS count FROM qc_first100_members');
  if (Number(count) >= GOAL) return res.status(409).json({ message: 'The First 100 places are already filled.' });

  const source = String(req.body?.source || 'direct').trim().slice(0, 40) || 'direct';
  const row = await db.insert('INSERT INTO qc_first100_members (user_id, source) VALUES (?, ?)', [req.user.id, source]);
  await audit(req, 'growth.first100_joined', 'first100_member', row.id, 'User joined QuickChat First 100', null, { source });
  const joined = Number(count) + 1;
  res.status(201).json({
    joined: true,
    position: joined,
    remaining: Math.max(0, GOAL - joined),
    referralCode: `QC${req.user.id}`,
    referralLink: `${String(process.env.PUBLIC_APP_URL || '').replace(/\/$/, '')}/register?ref=QC${req.user.id}`,
    message: joined <= GOAL
      ? `You are #${joined} in the QuickChat First 100.`
      : 'You joined QuickChat First 100.',
  });
}));

router.get('/admin/growth/first-100', requirePermission('analytics.view'), asyncRoute(async (_req, res) => {
  const total = await db.getCount('SELECT COUNT(*) AS count FROM qc_first100_members');
  const rows = await db.query(`SELECT m.id, m.user_id, m.source, m.joined_at,
      u.fullname, u.username, u.email, u.email_verified
    FROM qc_first100_members m JOIN users u ON u.id = m.user_id
    ORDER BY m.id ASC LIMIT 100`);
  res.json({
    goal: GOAL,
    joined: Number(total || 0),
    remaining: Math.max(0, GOAL - Number(total || 0)),
    members: rows,
  });
}));

module.exports = { router, initializeFirst100Tables };
