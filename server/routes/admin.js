router.post('/admin/roles', requirePermission('roles.create'), asyncRoute(async (req, res) => {
  const name = String(req.body?.name || '').trim().slice(0, 120);
  const key = String(req.body?.key || '').trim().toLowerCase().replace(/[^a-z0-9_-]/g, '_').slice(0, 80);
  const description = String(req.body?.description || '').trim().slice(0, 1000);
  const requested = Array.isArray(req.body?.permissions) ? [...new Set(req.body.permissions.map(String))] : [];
  if (!name || !/^[a-z0-9_-]{2,80}$/.test(key)) return res.status(400).json({ message: 'Provide a role name and a valid role key.' });
  const actorPermissions = await getPermissions(req.user.id);
  const allowed = requested.filter((p) => actorPermissions.includes('*') || actorPermissions.includes(p));
  if (allowed.length !== requested.length) return res.status(403).json({ message: 'You cannot grant permissions you do not hold.' });
  const role = await db.insert('INSERT INTO admin_roles (role_key, name, description, is_system) VALUES (?, ?, ?, 0)', [key, name, description]);
  for (const permission of allowed) {
    const row = await db.getOne('SELECT id FROM admin_permissions WHERE permission_key = ?', [permission]);
    if (row) await insertRolePermission(role.id, row.id);
  }
  await audit(req, 'role.created', 'role', role.id, 'Role created');
  res.status(201).json({ role: { id: role.id, key, name, permissions: allowed } });
}));

