const express = require('express');
const crypto = require('crypto');
const db = require('../database');
const { TypeSafeClient, noul } = require('@typesafe-ai/sdk');
const { notifyUser } = require('../notify');
const { getSetting } = require('../platform-settings');
const { asyncRoute } = require('./utils');

const router = express.Router();
const dateType = db.type === 'sqlite' ? 'DATETIME' : 'TIMESTAMP';
const idColumn = db.type === 'postgres'
  ? 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY'
  : db.type === 'mysql' ? 'INTEGER AUTO_INCREMENT PRIMARY KEY' : 'INTEGER PRIMARY KEY AUTOINCREMENT';
let jevClient;

const clean = (value, max = 5000) => String(value || '').replace(/\s+/g, ' ').trim().slice(0, max);
const parseJson = (value, fallback = []) => {
  try { return JSON.parse(value || ''); } catch (_) { return fallback; }
};
const fingerprint = (text) => crypto.createHash('sha256')
  .update(clean(text, 5000).toLowerCase().replace(/[^\p{L}\p{N}]+/gu, ' '))
  .digest('hex');

async function initializeCopyrightTables() {
  await db.query(`CREATE TABLE IF NOT EXISTS qc_copyright_assets (
    id ${idColumn},
    creator_id INTEGER NOT NULL,
    post_id INTEGER NOT NULL UNIQUE,
    fingerprint VARCHAR(64) NOT NULL,
    original_text TEXT,
    status VARCHAR(24) NOT NULL DEFAULT 'protected',
    created_at ${dateType} DEFAULT CURRENT_TIMESTAMP
  )`);
  await db.query(`CREATE TABLE IF NOT EXISTS qc_copyright_matches (
    id ${idColumn},
    asset_id INTEGER NOT NULL,
    matched_post_id INTEGER NOT NULL,
    matched_creator_id INTEGER NOT NULL,
    confidence REAL NOT NULL DEFAULT 0,
    assessment TEXT,
    status VARCHAR(24) NOT NULL DEFAULT 'new',
    model VARCHAR(80),
    created_at ${dateType} DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(asset_id, matched_post_id)
  )`);
  await db.query(`CREATE TABLE IF NOT EXISTS qc_copyright_actions (
    id ${idColumn},
    match_id INTEGER NOT NULL,
    creator_id INTEGER NOT NULL,
    action VARCHAR(32) NOT NULL,
    note TEXT,
    created_at ${dateType} DEFAULT CURRENT_TIMESTAMP
  )`);
}

async function requireCreator(req, res) {
  const creator = await db.getOne("SELECT user_id FROM qc_creator_applications WHERE user_id = ? AND status = 'active'", [req.user.id]);
  if (!creator) {
    res.status(403).json({ message: 'An active Creator Portal profile is required.' });
    return false;
  }
  return true;
}

async function getJev() {
  const enabled = String(await getSetting('typesafe_jev_enabled', process.env.TYPESAFE_JEV_ENABLED || 'true')).toLowerCase() !== 'false';
  const key = String(await getSetting('typesafe_api_key', process.env.TYPESAFE_API_KEY || '')).trim();
  const model = String(await getSetting('typesafe_jev_model', process.env.TYPESAFE_JEV_MODEL || 'jev-latest')).trim() || 'jev-latest';
  if (!enabled || !key) throw new Error('JEV is not enabled or TYPESAFE_API_KEY is missing in server configuration.');
  if (!jevClient || jevClientKey !== key) {
    process.env.TYPESAFE_API_KEY = key;
    jevClient = new TypeSafeClient();
    jevClientKey = key;
  }
  return { client: jevClient, model };
}
let jevClientKey = '';

router.get('/creator/copyright/available', asyncRoute(async (req, res) => {
  if (!await requireCreator(req, res)) return;
  const rows = await db.query(
    'SELECT p.id, p.body, p.kind, p.created_at FROM posts p WHERE p.author_id = ? AND NOT EXISTS (SELECT 1 FROM qc_copyright_assets a WHERE a.post_id = p.id) ORDER BY p.created_at DESC LIMIT 100',
    [req.user.id]
  );
  res.json({ items: rows.map((row) => ({ id: Number(row.id), text: row.body || '', kind: row.kind || 'text', createdAt: row.created_at })) });
}));

router.get('/creator/copyright', asyncRoute(async (req, res) => {
  if (!await requireCreator(req, res)) return;
  const assets = await db.query(
    `SELECT a.id, a.post_id, a.fingerprint, a.status, a.created_at, p.body, p.kind, p.media
       FROM qc_copyright_assets a JOIN posts p ON p.id = a.post_id
      WHERE a.creator_id = ? ORDER BY a.id DESC LIMIT 100`,
    [req.user.id]
  );
  const matches = await db.query(
    `SELECT m.id, m.asset_id, m.matched_post_id, m.matched_creator_id, m.confidence,
            m.assessment, m.status, m.model, m.created_at, p.body AS matched_text,
            u.username AS matched_username
       FROM qc_copyright_matches m
       JOIN qc_copyright_assets a ON a.id = m.asset_id
       JOIN posts p ON p.id = m.matched_post_id
       JOIN users u ON u.id = m.matched_creator_id
      WHERE a.creator_id = ? ORDER BY m.created_at DESC LIMIT 100`,
    [req.user.id]
  );
  res.json({
    assets: assets.map((row) => ({ id: Number(row.id), postId: Number(row.post_id), text: row.body || '', kind: row.kind || 'text', media: parseJson(row.media), status: row.status, createdAt: row.created_at })),
    matches: matches.map((row) => ({ id: Number(row.id), assetId: Number(row.asset_id), postId: Number(row.matched_post_id), creatorId: Number(row.matched_creator_id), username: row.matched_username, confidence: Number(row.confidence), assessment: row.assessment, status: row.status, text: row.matched_text || '', createdAt: row.created_at })),
  });
}));

router.post('/creator/copyright/protect/:postId', asyncRoute(async (req, res) => {
  if (!await requireCreator(req, res)) return;
  const postId = Number(req.params.postId);
  if (!Number.isSafeInteger(postId) || postId < 1) return res.status(400).json({ message: 'Invalid post ID.' });
  const post = await db.getOne('SELECT id, author_id, body, visibility FROM posts WHERE id = ?', [postId]);
  if (!post || Number(post.author_id) !== Number(req.user.id)) return res.status(404).json({ message: 'Only your own published posts can be protected.' });
  const digest = fingerprint(post.body);
  await db.query(
    `INSERT INTO qc_copyright_assets (creator_id, post_id, fingerprint, original_text)
     VALUES (?, ?, ?, ?)
     ${db.type === 'mysql' ? 'ON DUPLICATE KEY UPDATE fingerprint = VALUES(fingerprint), original_text = VALUES(original_text)' : 'ON CONFLICT(post_id) DO UPDATE SET fingerprint = EXCLUDED.fingerprint, original_text = EXCLUDED.original_text'}`,
    [req.user.id, postId, digest, clean(post.body)]
  );
  res.status(201).json({ message: 'Your post is registered in Copyright Guard.', postId, fingerprint: digest });
}));

router.post('/creator/copyright/scan/:assetId', asyncRoute(async (req, res) => {
  if (!await requireCreator(req, res)) return;
  const assetId = Number(req.params.assetId);
  const asset = await db.getOne(
    'SELECT a.*, p.body AS original_text FROM qc_copyright_assets a JOIN posts p ON p.id = a.post_id WHERE a.id = ? AND a.creator_id = ?',
    [assetId, req.user.id]
  );
  if (!asset) return res.status(404).json({ message: 'Protected work not found.' });
  const { client, model } = await getJev();
  const candidates = await db.query(
    `SELECT p.id, p.author_id, p.body, p.kind, p.created_at, u.username
       FROM posts p JOIN users u ON u.id = p.author_id
      WHERE p.id <> ? AND p.visibility = 'public' AND p.author_id <> ?
        AND p.body IS NOT NULL AND LENGTH(TRIM(p.body)) > 20
      ORDER BY p.created_at DESC LIMIT 40`,
    [asset.post_id, req.user.id]
  );
  const matches = [];
  for (const candidate of candidates) {
    if (fingerprint(candidate.body) === asset.fingerprint) {
      matches.push({ candidate, confidence: 1, assessment: 'Exact normalized caption match.' });
      continue;
    }
    const response = await client.systemOne({
      model,
      state: {
        original_work: clean(asset.original_text),
        candidate_work: clean(candidate.body),
        original_posted_at: String(asset.created_at || ''),
        candidate_posted_at: String(candidate.created_at || ''),
        candidate_is_public: true,
      },
      questions: {
        substantially_same: noul('Does the candidate contain substantial copied wording from the original, rather than merely sharing a topic, short phrase, or common expression? Judge only the supplied text.'),
      },
    });
    const answer = response.answers?.substantially_same;
    const confidence = Number(answer?.noul || 0);
    if (Number.isFinite(confidence) && confidence >= 0.72) {
      matches.push({
        candidate,
        confidence,
        assessment: 'JEV found substantial textual similarity. This is an automated lead for human review, not a legal finding.',
      });
    }
  }

  let created = 0;
  for (const match of matches) {
    const candidate = match.candidate;
    const prior = await db.getOne('SELECT id FROM qc_copyright_matches WHERE asset_id = ? AND matched_post_id = ?', [assetId, candidate.id]);
    await db.query(
      `INSERT INTO qc_copyright_matches (asset_id, matched_post_id, matched_creator_id, confidence, assessment, model)
       VALUES (?, ?, ?, ?, ?, ?)
       ${db.type === 'mysql' ? 'ON DUPLICATE KEY UPDATE confidence = VALUES(confidence), assessment = VALUES(assessment), model = VALUES(model)' : 'ON CONFLICT(asset_id, matched_post_id) DO UPDATE SET confidence = EXCLUDED.confidence, assessment = EXCLUDED.assessment, model = EXCLUDED.model'}`,
      [assetId, candidate.id, candidate.author_id, match.confidence, match.assessment, model]
    );
    if (!prior) {
      await notifyUser({
        userId: req.user.id,
        type: 'copyright_alert',
        text: `Copyright Guard found a possible text match on a public post (@${candidate.username || 'creator'}).`,
        push: { title: 'Copyright alert', body: 'JEV found a possible match. Review the evidence in Creator Studio.', url: '/creator/copyright', tag: `copyright-${assetId}-${candidate.id}` },
      });
      created += 1;
    }
  }
  res.json({ scanned: candidates.length, matches: matches.length, alertsCreated: created, model, scope: 'Public post text only. Media matching is not enabled by this integration.' });
}));

router.post('/creator/copyright/matches/:matchId/action', asyncRoute(async (req, res) => {
  if (!await requireCreator(req, res)) return;
  const matchId = Number(req.params.matchId);
  const action = clean(req.body?.action, 24).toLowerCase();
  const note = clean(req.body?.note, 1000);
  if (!Number.isSafeInteger(matchId) || !['confirm', 'dismiss', 'report'].includes(action)) {
    return res.status(400).json({ message: 'Choose confirm, dismiss or report.' });
  }
  const match = await db.getOne(
    'SELECT m.id FROM qc_copyright_matches m JOIN qc_copyright_assets a ON a.id = m.asset_id WHERE m.id = ? AND a.creator_id = ?',
    [matchId, req.user.id]
  );
  if (!match) return res.status(404).json({ message: 'Copyright match not found.' });
  const status = action === 'confirm' ? 'creator_confirmed' : action === 'dismiss' ? 'dismissed' : 'reported';
  await db.query('UPDATE qc_copyright_matches SET status = ? WHERE id = ?', [status, matchId]);
  await db.query('INSERT INTO qc_copyright_actions (match_id, creator_id, action, note) VALUES (?, ?, ?, ?)', [matchId, req.user.id, action, note]);
  res.json({ message: action === 'report' ? 'Your copyright report has been recorded for moderation review.' : action === 'confirm' ? 'You confirmed that this may be your work.' : 'Match dismissed.', status });
}));

module.exports = { router, initializeCopyrightTables };
