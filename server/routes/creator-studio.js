const express = require('express');
const db = require('../database');
const { asyncRoute } = require('./utils');
const { requirePermission } = require('./admin');
const creatorContentRoutes = require('./creator-content');

const router = express.Router();
router.use(creatorContentRoutes.router);
const dateType = db.type === 'sqlite' ? 'DATETIME' : 'TIMESTAMP';

async function initializeCreatorStudioTables() {
  await db.query(`CREATE TABLE IF NOT EXISTS qc_creator_applications (
    user_id INTEGER PRIMARY KEY,
    creator_name VARCHAR(100),
    niche VARCHAR(80),
    bio TEXT,
    status VARCHAR(20) NOT NULL DEFAULT 'active',
    created_at ${dateType} DEFAULT CURRENT_TIMESTAMP,
    updated_at ${dateType} DEFAULT CURRENT_TIMESTAMP
  )`);
  await db.query(`CREATE TABLE IF NOT EXISTS qc_growth_attribution (
    id ${db.type === 'postgres' ? 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : db.type === 'mysql' ? 'INTEGER AUTO_INCREMENT PRIMARY KEY' : 'INTEGER PRIMARY KEY AUTOINCREMENT'},
    user_id INTEGER NOT NULL UNIQUE,
    referrer_id INTEGER,
    source VARCHAR(60) NOT NULL DEFAULT 'direct',
    campaign VARCHAR(100),
    medium VARCHAR(60),
    landing_path VARCHAR(255),
    created_at ${dateType} DEFAULT CURRENT_TIMESTAMP
  )`);
}

async function recordAttribution(userId, payload = {}) {
  const code = clean(payload.referralCode || payload.ref, 40).toUpperCase();
  const match = code.match(/^QC(\d{1,12})$/);
  let referrerId = match ? Number(match[1]) : null;
  if (referrerId) {
    const validReferrer = await db.getOne('SELECT id FROM users WHERE id = ?', [referrerId]);
    if (!validReferrer || Number(referrerId) === Number(userId)) referrerId = null;
  }
  const source = clean(payload.source || payload.utm_source || (referrerId ? 'referral' : 'direct'), 60) || 'direct';
  const campaign = clean(payload.campaign || payload.utm_campaign, 100) || null;
  const medium = clean(payload.medium || payload.utm_medium, 60) || null;
  const landingPath = clean(payload.landingPath || payload.landing_path, 255) || null;
  await db.query('INSERT INTO qc_growth_attribution (user_id, referrer_id, source, campaign, medium, landing_path) VALUES (?, ?, ?, ?, ?, ?) ' + (db.type === 'mysql' ? 'ON DUPLICATE KEY UPDATE user_id = VALUES(user_id)' : 'ON CONFLICT(user_id) DO NOTHING'), [userId, referrerId && referrerId !== Number(userId) ? referrerId : null, source, campaign, medium, landingPath]);
}

function clean(value, max) {
  return String(value || '').trim().slice(0, max);
}

router.get('/creator-studio/me', asyncRoute(async (req, res) => {
  const user = await db.getOne('SELECT id, fullname, username, creator_account FROM users WHERE id = ?', [req.user.id]);
  if (!user) return res.status(404).json({ message: 'Account not found.' });
  const [application, posts, followers, following, referrals, qualified, attributed] = await Promise.all([
    db.getOne('SELECT creator_name, niche, bio, status, created_at FROM qc_creator_applications WHERE user_id = ?', [req.user.id]),
    db.getCount('SELECT COUNT(*) AS count FROM posts WHERE author_id = ?', [req.user.id]),
    db.getCount('SELECT COUNT(*) AS count FROM follows WHERE followed_id = ?', [req.user.id]),
    db.getCount('SELECT COUNT(*) AS count FROM follows WHERE follower_id = ?', [req.user.id]),
    db.getCount('SELECT COUNT(*) AS count FROM qc_reward_referrals WHERE referrer_id = ?', [req.user.id]),
    db.getCount("SELECT COUNT(*) AS count FROM qc_reward_referrals WHERE referrer_id = ? AND status = 'qualified'", [req.user.id]),
    db.getCount('SELECT COUNT(*) AS count FROM qc_growth_attribution WHERE referrer_id = ?', [req.user.id]),
  ]);
  const sources = await db.query(`SELECT source, campaign, COUNT(*) AS users
    FROM qc_growth_attribution WHERE referrer_id = ? GROUP BY source, campaign ORDER BY users DESC LIMIT 12`, [req.user.id]);
  res.json({
    isCreator: Number(user.creator_account || 0) === 1,
    profile: { fullName: user.fullname || '', username: user.username || '' },
    creator: application || null,
    metrics: { posts: Number(posts || 0), followers: Number(followers || 0), following: Number(following || 0),
      referrals: Number(referrals || 0), qualifiedReferrals: Number(qualified || 0), trackedSignups: Number(attributed || 0) },
    referralCode: `QC${req.user.id}`,
    referralLink: `${String(process.env.PUBLIC_APP_URL || '').replace(/\/$/, '')}/register?ref=QC${req.user.id}`,
    trackingLinks: {
      tiktok: `${String(process.env.PUBLIC_APP_URL || '').replace(/\/$/, '')}/register?ref=QC${req.user.id}&utm_source=tiktok&utm_medium=short_video&utm_campaign=creator_recruitment`,
      whatsapp: `${String(process.env.PUBLIC_APP_URL || '').replace(/\/$/, '')}/register?ref=QC${req.user.id}&utm_source=whatsapp&utm_medium=messaging&utm_campaign=creator_recruitment`,
      dm: `${String(process.env.PUBLIC_APP_URL || '').replace(/\/$/, '')}/register?ref=QC${req.user.id}&utm_source=creator_dm&utm_medium=direct_message&utm_campaign=creator_recruitment`,
    },
    referralSources: sources,
  });
}));

router.post('/creator-studio/activate', asyncRoute(async (req, res) => {
  const creatorName = clean(req.body?.creatorName, 100);
  const niche = clean(req.body?.niche, 80);
  const bio = clean(req.body?.bio, 500);
  if (!creatorName || !niche) return res.status(400).json({ message: 'Enter your creator name and choose a content category.' });
  await db.query(`INSERT INTO qc_creator_applications (user_id, creator_name, niche, bio, status)
    VALUES (?, ?, ?, ?, 'active')
    ${db.type === 'mysql' ? 'ON DUPLICATE KEY UPDATE creator_name = VALUES(creator_name), niche = VALUES(niche), bio = VALUES(bio), status = \'active\', updated_at = CURRENT_TIMESTAMP' : 'ON CONFLICT(user_id) DO UPDATE SET creator_name = excluded.creator_name, niche = excluded.niche, bio = excluded.bio, status = \'active\', updated_at = CURRENT_TIMESTAMP'}`,
  [req.user.id, creatorName, niche, bio]);
  await db.update('UPDATE users SET creator_account = 1 WHERE id = ?', [req.user.id]);
  res.json({ message: 'Creator account activated. Your existing profile and posts are unchanged.', isCreator: true });
}));


router.get('/admin/growth/attribution', requirePermission('analytics.view'), asyncRoute(async (_req, res) => {
  const [total, sources, campaigns, recent] = await Promise.all([
    db.getCount('SELECT COUNT(*) AS count FROM qc_growth_attribution'),
    db.query('SELECT source, COUNT(*) AS users FROM qc_growth_attribution GROUP BY source ORDER BY users DESC'),
    db.query("SELECT COALESCE(campaign, '(no campaign tag)') AS campaign, COALESCE(source, 'direct') AS source, COUNT(*) AS users FROM qc_growth_attribution GROUP BY campaign, source ORDER BY users DESC LIMIT 30"),
    db.query(`SELECT a.user_id, a.referrer_id, a.source, a.campaign, a.medium, a.landing_path, a.created_at,
      u.fullname, u.username, u.email
      FROM qc_growth_attribution a LEFT JOIN users u ON u.id = a.user_id
      ORDER BY a.id DESC LIMIT 100`),
  ]);
  res.json({ total: Number(total || 0), sources, campaigns, recent });
}));

module.exports = { router, initializeCreatorStudioTables, recordAttribution };
