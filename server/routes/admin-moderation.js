const express = require('express');
const { db, asyncRoute } = require('./utils');
const { requirePermission, audit } = require('./admin');

const router = express.Router();
const idColumn = db.type === 'postgres'
  ? 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY'
  : db.type === 'mysql'
    ? 'INTEGER AUTO_INCREMENT PRIMARY KEY'
    : 'INTEGER PRIMARY KEY AUTOINCREMENT';
const dateType = db.type === 'sqlite' ? 'DATETIME' : 'TIMESTAMP';

async function initializePostModeration() {
  await db.query(`CREATE TABLE IF NOT EXISTS admin_post_moderation (
    id ${idColumn}, post_id INTEGER NOT NULL UNIQUE, original_visibility VARCHAR(30) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'removed', policy_key VARCHAR(80),
    reason TEXT NOT NULL, moderator_id INTEGER NOT NULL, moderated_at ${dateType} DEFAULT CURRENT_TIMESTAMP,
    restored_by INTEGER, restored_at ${dateType}
  )`);
}

router.get('/admin/moderation/posts', requirePermission('posts.view'), asyncRoute(async (req, res) => {
  const page = Math.max(1, Math.min(100000, Number.parseInt(req.query.page, 10) || 1));
  const limit = Math.max(10, Math.min(50, Number.parseInt(req.query.limit, 10) || 20));
  const search = String(req.query.search || '').trim().slice(0, 100);
  const status = ['active', 'removed', 'all'].includes(String(req.query.status)) ? String(req.query.status) : 'active';
  const where = [];
  const params = [];
  if (status === 'active') where.push("COALESCE(m.status, 'active') = 'active'");
  if (status === 'removed') where.push("m.status = 'removed'");
  if (search) {
    where.push('(CAST(p.id AS CHAR) LIKE ? OR LOWER(p.body) LIKE LOWER(?) OR LOWER(u.username) LIKE LOWER(?) OR LOWER(u.fullname) LIKE LOWER(?))');
    params.push(`%${search}%`, `%${search}%`, `%${search}%`, `%${search}%`);
  }
  const filter = where.length ? `WHERE ${where.join(' AND ')}` : '';
  const total = await db.getCount(`SELECT COUNT(*) AS count FROM posts p JOIN users u ON u.id = p.author_id LEFT JOIN admin_post_moderation m ON m.post_id = p.id ${filter}`, params);
  const posts = await db.query(
    `SELECT p.id, p.author_id, p.body, p.kind, p.category, p.media, p.visibility, p.created_at,
            u.username, u.fullname, u.avatar_url, u.picture, m.status AS moderation_status,
            m.policy_key, m.reason AS moderation_reason, m.moderated_at
       FROM posts p JOIN users u ON u.id = p.author_id
       LEFT JOIN admin_post_moderation m ON m.post_id = p.id
       ${filter}
      ORDER BY p.created_at DESC, p.id DESC LIMIT ? OFFSET ?`,
    [...params, limit, (page - 1) * limit],
  );
  res.setHeader('Cache-Control', 'private, no-store');
  res.json({ posts: posts.map((post) => {
    let media = [];
    try { media = Array.isArray(post.media) ? post.media : JSON.parse(post.media || '[]'); } catch (_) {}
    return { ...post, media: Array.isArray(media) ? media : [], moderation_status: post.moderation_status || 'active' };
  }), pagination: { page, limit, total, pages: Math.max(1, Math.ceil(total / limit)) } });
}));

router.post('/admin/moderation/posts/:id/remove', requirePermission('posts.remove'), asyncRoute(async (req, res) => {
  const id = Number(req.params.id);
  const reason = String(req.body?.reason || '').trim().slice(0, 2000);
  const policyKey = String(req.body?.policyKey || 'terms_violation').trim().slice(0, 80);
  if (!Number.isSafeInteger(id) || id < 1 || !reason) return res.status(400).json({ message: 'A valid post and policy reason are required.' });
  const post = await db.getOne('SELECT id, visibility FROM posts WHERE id = ?', [id]);
  if (!post) return res.status(404).json({ message: 'Post not found.' });
  const prior = await db.getOne('SELECT * FROM admin_post_moderation WHERE post_id = ?', [id]);
  if (prior?.status === 'removed') return res.status(409).json({ message: 'This post has already been removed.' });
  if (prior) {
    await db.update("UPDATE admin_post_moderation SET status = 'removed', reason = ?, policy_key = ?, moderator_id = ?, moderated_at = CURRENT_TIMESTAMP, restored_by = NULL, restored_at = NULL WHERE post_id = ?", [reason, policyKey, req.user.id, id]);
  } else {
    await db.insert('INSERT INTO admin_post_moderation (post_id, original_visibility, status, policy_key, reason, moderator_id) VALUES (?, ?, ?, ?, ?, ?)', [id, post.visibility || 'public', 'removed', policyKey, reason, req.user.id]);
  }
  await db.update("UPDATE posts SET visibility = 'moderated_removed' WHERE id = ?", [id]);
  await audit(req, 'post.removed', 'post', id, reason, { visibility: post.visibility }, { visibility: 'moderated_removed', policyKey });
  res.json({ message: 'Post removed from QuickChat feeds.' });
}));

router.post('/admin/moderation/posts/:id/restore', requirePermission('posts.restore'), asyncRoute(async (req, res) => {
  const id = Number(req.params.id);
  const reason = String(req.body?.reason || '').trim().slice(0, 2000);
  if (!Number.isSafeInteger(id) || id < 1 || !reason) return res.status(400).json({ message: 'A restoration reason is required.' });
  const record = await db.getOne("SELECT * FROM admin_post_moderation WHERE post_id = ? AND status = 'removed'", [id]);
  if (!record) return res.status(404).json({ message: 'Removed post not found.' });
  await db.update('UPDATE posts SET visibility = ? WHERE id = ?', [record.original_visibility || 'public', id]);
  await db.update("UPDATE admin_post_moderation SET status = 'restored', restored_by = ?, restored_at = CURRENT_TIMESTAMP WHERE post_id = ?", [req.user.id, id]);
  await audit(req, 'post.restored', 'post', id, reason, { status: 'removed' }, { status: 'restored', visibility: record.original_visibility || 'public' });
  res.json({ message: 'Post restored to its original visibility.' });
}));

module.exports = { router, initializePostModeration };
