async function addMissingPaymentColumns() {
  const columnsFor = async (table) => {
    if (db.type === 'sqlite') {
      return new Set((await db.query(`PRAGMA table_info(${table})`)).map((row) => row.name.toLowerCase()));
    }
    if (db.type === 'postgres') {
      return new Set((await db.query(
        'SELECT column_name FROM information_schema.columns WHERE table_schema = current_schema() AND table_name = ?',
        [table],
      )).map((row) => row.column_name.toLowerCase()));
    }
    return new Set((await db.query(`SHOW COLUMNS FROM ${table}`)).map((row) => row.Field.toLowerCase()));
  };

  const migrations = [
    ['payment_checkouts', { flutterwave_tx_ref: 'VARCHAR(120)' }],
    ['payment_transactions', { flutterwave_transaction_id: 'VARCHAR(100)' }],
  ];
  for (const [table, additions] of migrations) {
    const columns = await columnsFor(table);
    for (const [column, type] of Object.entries(additions)) {
      if (!columns.has(column)) await db.query(`ALTER TABLE ${table} ADD COLUMN ${column} ${type}`);
    }
  }
}

