const db = require('./database');

const WINDOW_MS = 60_000;
const MAX_REQUESTS_PER_WINDOW = 120;
const MAX_AUTH_REQUESTS_PER_WINDOW = 12;
const botBuckets = new Map();
const trafficBuckets = new Map();
const BOT_PATTERNS = [
  /curl\//i, /wget\//i, /python-requests/i, /scrapy/i, /httpclient/i,
  /headlesschrome/i, /phantomjs/i, /selenium/i, /playwright/i, /puppeteer/i,
  /libwww-perl/i, /go-http-client/i, /java\/\d/i, /axios\/\d/i,
];

function clientIp(req) {
  return String(req.ip || req.socket?.remoteAddress || '').trim().slice(0, 64) || 'unknown';
}

function botScore(req, recentCount = 0) {
  const ua = String(req.get('user-agent') || '');
  let score = 0;
  const signals = [];
  if (!ua) { score += 50; signals.push('missing_user_agent'); }
  for (const pattern of BOT_PATTERNS) {
    if (pattern.test(ua)) { score += 70; signals.push('automation_user_agent'); break; }
  }
  if (recentCount > MAX_REQUESTS_PER_WINDOW) { score += 40; signals.push('request_burst'); }
  if (recentCount > MAX_REQUESTS_PER_WINDOW * 2) { score += 30; signals.push('request_flood'); }
  if (req.method !== 'GET' && !req.get('origin') && !req.get('referer')) {
    score += 10; signals.push('non_browser_mutation');
  }
  return { score: Math.min(score, 100), signals };
}

function isAuthPath(pathname) {
  return ['/auth/register', '/auth/login', '/auth/google', '/traffic/landing'].includes(pathname);
}

function getBucket(map, key) {
  const now = Date.now();
  let bucket = map.get(key);
  if (!bucket || now - bucket.startedAt >= WINDOW_MS) {
    bucket = { startedAt: now, count: 0 };
    map.set(key, bucket);
  }
  bucket.count += 1;
  if (map.size > 5000) {
    for (const [entryKey, entry] of map) {
      if (now - entry.startedAt >= WINDOW_MS) map.delete(entryKey);
    }
  }
  return bucket.count;
}

async function initializeSecurityTables() {
  const idColumn = db.type === 'postgres'
    ? 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY'
    : db.type === 'mysql'
      ? 'INTEGER AUTO_INCREMENT PRIMARY KEY'
      : 'INTEGER PRIMARY KEY AUTOINCREMENT';
  const dateType = db.type === 'sqlite' ? 'DATETIME' : 'TIMESTAMP';

  const statements = [
    `CREATE TABLE IF NOT EXISTS traffic_events (
      id ${idColumn},
      event_type VARCHAR(30) NOT NULL,
      page VARCHAR(120),
      ip_address VARCHAR(64) NOT NULL,
      user_id INTEGER,
      user_agent TEXT,
      referrer TEXT,
      is_bot INTEGER NOT NULL DEFAULT 0,
      bot_score INTEGER NOT NULL DEFAULT 0,
      created_at ${dateType} DEFAULT CURRENT_TIMESTAMP
    )`,
    `CREATE TABLE IF NOT EXISTS bot_detection_events (
      id ${idColumn},
      ip_address VARCHAR(64) NOT NULL,
      path VARCHAR(255) NOT NULL,
      method VARCHAR(10) NOT NULL,
      score INTEGER NOT NULL DEFAULT 0,
      signals TEXT,
      user_agent TEXT,
      blocked INTEGER NOT NULL DEFAULT 0,
      created_at ${dateType} DEFAULT CURRENT_TIMESTAMP
    )`,
  ];
  for (const statement of statements) await db.query(statement);

  const indexes = [
    ['traffic_events_type_date_idx', 'traffic_events (event_type, created_at)', false],
    ['traffic_events_ip_date_idx', 'traffic_events (ip_address, created_at)', false],
    ['traffic_events_user_idx', 'traffic_events (user_id, created_at)', false],
    ['bot_detection_ip_date_idx', 'bot_detection_events (ip_address, created_at)', false],
    ['bot_detection_score_date_idx', 'bot_detection_events (score, created_at)', false],
  ];
  for (const [name, target, unique] of indexes) {
    if (db.type === 'mysql') {
      const exists = await db.getOne(
        'SELECT index_name FROM information_schema.statistics WHERE table_schema = DATABASE() AND index_name = ?',
        [name],
      );
      if (!exists) await db.query(`CREATE ${unique ? 'UNIQUE ' : ''}INDEX ${name} ON ${target}`);
    } else {
      await db.query(`CREATE ${unique ? 'UNIQUE ' : ''}INDEX IF NOT EXISTS ${name} ON ${target}`);
    }
  }
}

async function recordTraffic(req, { eventType, page, userId = null, bot = null } = {}) {
  try {
    const detection = bot || { score: 0 };
    await db.insert(
      `INSERT INTO traffic_events
        (event_type, page, ip_address, user_id, user_agent, referrer, is_bot, bot_score)
       VALUES (?, ?, ?, ?, ?, ?, ?, ?)`,
      [
        eventType,
        page || null,
        clientIp(req),
        userId,
        String(req.get('user-agent') || '').slice(0, 1000) || null,
        String(req.get('referer') || '').slice(0, 1000) || null,
        detection.score >= 70 ? 1 : 0,
        detection.score,
      ],
    );
  } catch (error) {
    console.warn('[Traffic] Could not record event:', error.message);
  }
}

function botDetector() {
  return async (req, res, next) => {
    const ip = clientIp(req);
    const count = getBucket(botBuckets, ip);
    const detection = botScore(req, count);
    req.botDetection = detection;
    res.setHeader('X-QuickChat-Bot-Check', detection.score >= 70 ? 'flagged' : 'passed');

    const shouldBlock = detection.score >= 70 && isAuthPath(req.path);
    if (detection.score >= 70 || shouldBlock) {
      try {
        await db.insert(
          `INSERT INTO bot_detection_events
            (ip_address, path, method, score, signals, user_agent, blocked)
           VALUES (?, ?, ?, ?, ?, ?, ?)`,
          [
            ip,
            String(req.originalUrl || req.path).slice(0, 255),
            req.method,
            detection.score,
            JSON.stringify(detection.signals),
            String(req.get('user-agent') || '').slice(0, 1000) || null,
            shouldBlock ? 1 : 0,
          ],
        );
      } catch (error) {
        console.warn('[BotDetector] Could not record detection:', error.message);
      }
    }

    if (shouldBlock) {
      return res.status(429).json({
        message: 'QuickChat could not verify this request. Please use a normal browser and try again shortly.',
        code: 'BOT_DETECTED',
      });
    }

    if (isAuthPath(req.path)) {
      const authCount = getBucket(trafficBuckets, ip);
      if (authCount > MAX_AUTH_REQUESTS_PER_WINDOW) {
        return res.status(429).json({
          message: 'Too many sign-in or registration attempts from this connection. Please try again later.',
          code: 'RATE_LIMITED',
        });
      }
    }

    return next();
  };
}

function trafficRouter() {
  const express = require('express');
  const router = express.Router();
  router.post('/traffic/landing', async (req, res) => {
    const page = String(req.body?.page || '').trim();
    if (!['/', '/login', '/register'].includes(page)) {
      return res.status(400).json({ message: 'Traffic page is not supported.' });
    }
    await recordTraffic(req, {
      eventType: 'landing_view',
      page,
      bot: req.botDetection,
    });
    return res.status(204).end();
  });
  router.post('/traffic/page-view', async (req, res) => {
    const rawPage = String(req.body?.page || '').trim();
    const page = rawPage.split(/[?#]/, 1)[0].slice(0, 120);
    if (!page.startsWith('/') || page.startsWith('//')) {
      return res.status(400).json({ message: 'A valid QuickChat page path is required.' });
    }
    await recordTraffic(req, {
      eventType: 'page_view',
      page: page || '/',
      bot: req.botDetection,
    });
    return res.status(204).end();
  });
  return router;
}

async function recordRegistration(req, userId) {
  await recordTraffic(req, { eventType: 'registration', page: '/register', userId, bot: req.botDetection });
}

function describeVisitor(userAgent) {
  const ua = String(userAgent || '');
  const device = /iPad|Tablet|PlayBook|Silk/i.test(ua)
    ? 'Tablet'
    : /Mobile|Android|iPhone|iPod|IEMobile|Opera Mini/i.test(ua)
      ? 'Mobile'
      : ua ? 'Desktop' : 'Unknown';
  let browser = 'Unknown';
  if (/Edg\//i.test(ua)) browser = 'Edge';
  else if (/OPR\//i.test(ua)) browser = 'Opera';
  else if (/Firefox\//i.test(ua)) browser = 'Firefox';
  else if (/Chrome\//i.test(ua)) browser = 'Chrome';
  else if (/Safari\//i.test(ua)) browser = 'Safari';
  let operatingSystem = 'Unknown';
  if (/Windows NT/i.test(ua)) operatingSystem = 'Windows';
  else if (/Android/i.test(ua)) operatingSystem = 'Android';
  else if (/iPhone|iPad|iPod/i.test(ua)) operatingSystem = 'iOS';
  else if (/Mac OS X/i.test(ua)) operatingSystem = 'macOS';
  else if (/Linux/i.test(ua)) operatingSystem = 'Linux';
  return { device, browser, operatingSystem };
}

async function getTrafficVisits({ page = 1, limit = 50, ip = '', path = '', from = '', to = '' } = {}) {
  const safePage = Math.max(1, Math.min(100000, Number(page) || 1));
  const safeLimit = Math.max(10, Math.min(100, Number(limit) || 50));
  const offset = (safePage - 1) * safeLimit;
  const clauses = ["event_type IN ('page_view', 'landing_view', 'registration')"];
  const params = [];
  if (ip) { clauses.push('ip_address LIKE ?'); params.push('%' + String(ip).slice(0, 64) + '%'); }
  if (path) { clauses.push('page LIKE ?'); params.push('%' + String(path).slice(0, 120) + '%'); }
  if (from) { clauses.push('created_at >= ?'); params.push(String(from).slice(0, 10) + ' 00:00:00'); }
  if (to) { clauses.push('created_at <= ?'); params.push(String(to).slice(0, 10) + ' 23:59:59'); }
  const where = clauses.join(' AND ');
  const [countRows, rows] = await Promise.all([
    db.query('SELECT COUNT(*) AS total FROM traffic_events WHERE ' + where, params),
    db.query(
      'SELECT id, event_type, page, ip_address, user_agent, referrer, created_at, is_bot, bot_score FROM traffic_events WHERE ' +
      where + ' ORDER BY created_at DESC, id DESC LIMIT ? OFFSET ?',
      [...params, safeLimit, offset],
    ),
  ]);
  return {
    page: safePage,
    limit: safeLimit,
    total: Number(countRows[0]?.total || 0),
    visits: rows.map((row) => ({
      id: row.id,
      eventType: row.event_type || 'page_view',
      page: row.page || '/',
      ip: row.ip_address || 'Unknown',
      timestamp: row.created_at,
      referrer: row.referrer || '',
      isBot: Boolean(Number(row.is_bot || 0)),
      botScore: Number(row.bot_score || 0),
      ...describeVisitor(row.user_agent),
      networkProvider: 'Not available',
    })),
  };
}

async function getTrafficOverview() {
  const days = 30;
  const dateFilter = db.type === 'sqlite'
    ? "datetime('now', '-30 days')"
    : db.type === 'mysql'
      ? 'DATE_SUB(CURRENT_TIMESTAMP, INTERVAL 30 DAY)'
      : "CURRENT_TIMESTAMP - INTERVAL '30 days'";

  const [registrations, landingViews, botEvents, topIps, daily] = await Promise.all([
    db.query(
      `SELECT COUNT(*) AS count,
              COUNT(DISTINCT ip_address) AS unique_ips
         FROM traffic_events
        WHERE event_type = 'registration' AND created_at >= ${dateFilter}`,
    ),
    db.query(
      `SELECT page, COUNT(*) AS count, COUNT(DISTINCT ip_address) AS unique_ips
         FROM traffic_events
        WHERE event_type = 'landing_view' AND created_at >= ${dateFilter}
        GROUP BY page ORDER BY count DESC`,
    ),
    db.query(
      `SELECT COUNT(*) AS count, SUM(CASE WHEN blocked = 1 THEN 1 ELSE 0 END) AS blocked
         FROM bot_detection_events WHERE created_at >= ${dateFilter}`,
    ),
    db.query(
      `SELECT ip_address, COUNT(*) AS registrations, MAX(created_at) AS last_registration
         FROM traffic_events
        WHERE event_type = 'registration' AND created_at >= ${dateFilter}
        GROUP BY ip_address ORDER BY registrations DESC, last_registration DESC
        LIMIT 50`,
    ),
    db.query(
      `SELECT ${dateBucketSql()} AS day, COUNT(*) AS registrations, COUNT(DISTINCT ip_address) AS unique_ips
         FROM traffic_events
        WHERE event_type = 'registration' AND created_at >= ${dateFilter}
        GROUP BY ${dateBucketSql()} ORDER BY day DESC
        LIMIT 31`,
    ),
  ]);

  return {
    periodDays: days,
    registrations: Number(registrations[0]?.count || 0),
    uniqueRegistrationIps: Number(registrations[0]?.unique_ips || 0),
    landingViews: landingViews.map((row) => ({ page: row.page, count: Number(row.count || 0), uniqueIps: Number(row.unique_ips || 0) })),
    botDetections: Number(botEvents[0]?.count || 0),
    blockedBotRequests: Number(botEvents[0]?.blocked || 0),
    topRegistrationIps: topIps.map((row) => ({ ip: row.ip_address, registrations: Number(row.registrations || 0), lastRegistration: row.last_registration })),
    dailyRegistrations: daily.map((row) => ({ day: row.day, registrations: Number(row.registrations || 0), uniqueIps: Number(row.unique_ips || 0) })),
  };
}

function dateBucketSql() {
  if (db.type === 'sqlite') return "strftime('%Y-%m-%d', created_at)";
  if (db.type === 'mysql') return "DATE_FORMAT(created_at, '%Y-%m-%d')";
  return "TO_CHAR(created_at, 'YYYY-MM-DD')";
}

