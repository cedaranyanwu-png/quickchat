
const db = require('./database');

async function initializeCreatorContentTables() {
  const idColumn = db.type === 'postgres'
    ? 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY'
    : db.type === 'mysql'
      ? 'INTEGER AUTO_INCREMENT PRIMARY KEY'
      : 'INTEGER PRIMARY KEY AUTOINCREMENT';
  const dateType = db.type === 'sqlite' ? 'DATETIME' : 'TIMESTAMP';

  await db.query(`CREATE TABLE IF NOT EXISTS qc_scheduled_creator_posts (
    id ${idColumn},
    creator_id INTEGER NOT NULL,
    body TEXT NOT NULL DEFAULT '',
    media TEXT,
    category VARCHAR(80),
    hashtags TEXT,
    target_interests TEXT,
    topics TEXT,
    keywords TEXT,
    audience_signals TEXT,
    recommendation_interests TEXT,
    destination VARCHAR(20) NOT NULL DEFAULT 'profile',
    community_id INTEGER,
    visibility VARCHAR(20) NOT NULL DEFAULT 'public',
    scheduled_at ${dateType} NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'scheduled',
    analysis_status VARCHAR(20) NOT NULL DEFAULT 'ready',
    published_post_id INTEGER,
    published_at ${dateType},
    created_at ${dateType} DEFAULT CURRENT_TIMESTAMP,
    updated_at ${dateType} DEFAULT CURRENT_TIMESTAMP
  )`);

  if (db.type === 'mysql') {
    await db.query('CREATE INDEX qc_scheduled_creator_posts_creator_status_idx ON qc_scheduled_creator_posts (creator_id, status, scheduled_at)');
  } else {
    await db.query('CREATE INDEX IF NOT EXISTS qc_scheduled_creator_posts_creator_status_idx ON qc_scheduled_creator_posts (creator_id, status, scheduled_at)');
  }
}

module.exports = { initializeCreatorContentTables };
